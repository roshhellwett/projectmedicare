-- 6. RPC Function for POS Checkout (Atomic Stock Reduction & Invoice Creation)
CREATE OR REPLACE FUNCTION public.create_invoice(
    p_invoice_no TEXT,
    p_patient_name TEXT,
    p_doctor_name TEXT,
    p_subtotal NUMERIC,
    p_gst_total NUMERIC,
    p_discount NUMERIC,
    p_net_amount NUMERIC,
    p_items JSONB -- Array of {batch_id, quantity, rate, gst_percent, gst_amount, amount}
) RETURNS BIGINT AS $$
DECLARE
    v_invoice_id BIGINT;
    v_item JSONB;
    v_batch_id BIGINT;
    v_quantity NUMERIC;
BEGIN
    -- Insert invoice
    INSERT INTO public.invoices (invoice_no, patient_name, doctor_name, subtotal, gst_total, discount, net_amount, status)
    VALUES (p_invoice_no, p_patient_name, p_doctor_name, p_subtotal, p_gst_total, p_discount, p_net_amount, 'completed')
    RETURNING id INTO v_invoice_id;

    -- Process each item
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_batch_id := (v_item->>'batch_id')::BIGINT;
        v_quantity := (v_item->>'quantity')::NUMERIC;

        -- Check and deduct stock atomically
        UPDATE public.medicine_batches
        SET stock = stock - v_quantity
        WHERE id = v_batch_id AND stock >= v_quantity;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Insufficient stock for batch_id %', v_batch_id;
        END IF;

        -- Insert line item
        INSERT INTO public.invoice_items (invoice_id, batch_id, quantity, rate, gst_percent, gst_amount, amount)
        VALUES (
            v_invoice_id, 
            v_batch_id, 
            v_quantity, 
            (v_item->>'rate')::NUMERIC, 
            (v_item->>'gst_percent')::NUMERIC, 
            (v_item->>'gst_amount')::NUMERIC, 
            (v_item->>'amount')::NUMERIC
        );
    END LOOP;

    RETURN v_invoice_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
GRANT EXECUTE ON FUNCTION public.create_invoice TO authenticated, service_role;

-- 7. RPC Function for Invoice Cancellation (Atomic Stock Return)
CREATE OR REPLACE FUNCTION public.cancel_invoice(p_invoice_id BIGINT) 
RETURNS BOOLEAN AS $$
DECLARE
    v_status TEXT;
    v_item RECORD;
BEGIN
    -- Check current status
    SELECT status INTO v_status FROM public.invoices WHERE id = p_invoice_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Invoice not found';
    END IF;
    IF v_status = 'cancelled' THEN
        RAISE EXCEPTION 'Invoice is already cancelled';
    END IF;

    -- Update invoice status
    UPDATE public.invoices SET status = 'cancelled', updated_at = NOW() WHERE id = p_invoice_id;

    -- Return stock for all items
    FOR v_item IN SELECT batch_id, quantity FROM public.invoice_items WHERE invoice_id = p_invoice_id
    LOOP
        IF v_item.batch_id IS NOT NULL THEN
            UPDATE public.medicine_batches
            SET stock = stock + v_item.quantity, updated_at = NOW()
            WHERE id = v_item.batch_id;
        END IF;
    END LOOP;

    RETURN TRUE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
GRANT EXECUTE ON FUNCTION public.cancel_invoice TO authenticated, service_role;
