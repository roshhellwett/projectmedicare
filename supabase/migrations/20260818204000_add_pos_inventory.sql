-- 1. Create medicine_batches table
CREATE TABLE IF NOT EXISTS public.medicine_batches (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    medicine_id BIGINT NOT NULL REFERENCES public.medicines(id) ON DELETE CASCADE,
    barcode TEXT UNIQUE,
    batch_number TEXT,
    expiry_date TEXT,
    buying_price NUMERIC,
    selling_price NUMERIC,
    mrp NUMERIC,
    purchase NUMERIC,
    sale NUMERIC,
    stock NUMERIC NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Enable RLS for batches
ALTER TABLE public.medicine_batches ENABLE ROW LEVEL SECURITY;
CREATE POLICY "medicine_batches public read" ON public.medicine_batches FOR SELECT USING (true);
CREATE POLICY "medicine_batches admin all" ON public.medicine_batches USING (auth.role() = 'authenticated' OR auth.role() = 'service_role');
GRANT ALL ON public.medicine_batches TO service_role;
GRANT ALL ON public.medicine_batches TO authenticated;
GRANT SELECT ON public.medicine_batches TO anon;

